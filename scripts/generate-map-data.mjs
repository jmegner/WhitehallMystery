import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import process from 'node:process'

const root = resolve(import.meta.dirname, '..')
const sourceDirectory = resolve(root, 'src/data/whitehall')
const destination = resolve(sourceDirectory, 'generated.ts')
const sources = [
  ['alleyGroupsRaw', 'alley_groups.jsonl'],
  ['circlesRaw', 'circles.jsonl'],
  ['connectionsRaw', 'connections.jsonl'],
  ['squaresRaw', 'squares.jsonl'],
  ['waterGroupsRaw', 'water_groups.jsonl'],
]

const declarations = await Promise.all(sources.map(async ([exportName, fileName]) => {
  const contents = await readFile(resolve(sourceDirectory, fileName), 'utf8')
  return `export const ${exportName} = ${JSON.stringify(contents.replaceAll('\r\n', '\n'))}\n`
}))
const output = `// Generated by scripts/generate-map-data.mjs. Do not edit by hand.\n${declarations.join('')}`

if (process.argv.includes('--check')) {
  const existing = await readFile(destination, 'utf8').catch(() => '')
  if (existing !== output) {
    console.error('src/data/whitehall/generated.ts is stale. Run npm run generate:map-data.')
    process.exitCode = 1
  }
} else {
  await writeFile(destination, output)
}
