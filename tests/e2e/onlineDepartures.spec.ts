    expect(new URLSearchParams(new URL(jackInvitation).hash.slice(1)).get('role')).toBe('jack')
    await newJack.goto(jackInvitation)
    await expect(newJack.getByRole('heading', { name: 'Jack: Choose the Starting Location' })).toBeVisible()
    await newJack.getByLabel('Secret Discovery Locations').getByRole('button').first().click()
    await newJack.getByLabel('Legal Jack destinations').getByRole('button').first().click()
    await expect(newInvestigators.locator('.online-departure')).toBeVisible()
    await newJack.getByRole('button', { name: 'Record move privately' }).click()
    await expect(newInvestigators.getByRole('heading', { name: 'Yellow Investigator: Move' })).toBeVisible()
    await expect(newInvestigators.locator('.online-departure')).toHaveCount(0)
    expect((await post(request, origin, jackSession, { type: 'status' })).status()).toBe(401)
    await newInvestigators.getByRole('button', { name: 'Resume game', exact: true }).click()
    await expect(onlineEntry(newInvestigators)).not.toContainText('Opponent left the game')
