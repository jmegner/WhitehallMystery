test('online departures: a lost leave acknowledgement keeps the entry until an idempotent retry succeeds', async ({ page, request }) => {
  const session = await start(page)
  const origin = new URL(page.url()).origin
  await page.getByRole('button', { name: 'Resume game', exact: true }).click()
  const requestIds: string[] = []
  let loseResponse = true
  await page.route('**/session', async route => {
    const body = route.request().postDataJSON()
    if (body?.type !== 'leave') { await route.continue(); return }
    requestIds.push(body.requestId)
    if (loseResponse) {
      loseResponse = false
      const result = await route.fetch()
      expect(result.status()).toBe(200)
      await route.abort('failed')
    } else await route.continue()
  })
  page.once('dialog', dialog => dialog.accept())
  await onlineEntry(page).getByRole('button', { name: 'Leave', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'saved entry has been kept' })).toBeVisible()
  await expect(onlineEntry(page)).toHaveCount(1)
  expect((await post(request, origin, session, { type: 'status' })).status()).toBe(401)
  page.once('dialog', dialog => dialog.accept())
  await onlineEntry(page).getByRole('button', { name: 'Leave', exact: true }).click()
  await expect(onlineEntry(page)).toHaveCount(0)
  expect(requestIds).toHaveLength(2)
  expect(requestIds[1]).toBe(requestIds[0])
  await page.reload()
  await expect(onlineEntry(page)).toHaveCount(0)
})
